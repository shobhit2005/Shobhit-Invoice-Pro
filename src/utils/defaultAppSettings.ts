export function mergeAppSettings(saved?: Partial<AppSettings> | null): AppSettings {
  if (!saved) return DEFAULT_APP_SETTINGS;
  return {
    general: {
      ...DEFAULT_APP_SETTINGS.general,
      ...(saved.general || {}),
      dashboardWidgets: {
        ...DEFAULT_APP_SETTINGS.general.dashboardWidgets!,
        ...(saved.general?.dashboardWidgets || {}),
      },
    },
    transaction: { ...DEFAULT_APP_SETTINGS.transaction, ...(saved.transaction || {}) },
    print: { ...DEFAULT_APP_SETTINGS.print, ...(saved.print || {}) },
    gst: { ...DEFAULT_APP_SETTINGS.gst, ...(saved.gst || {}) },
    message: {
      ...DEFAULT_APP_SETTINGS.message,
      ...(saved.message || {}),
      autoFor: { ...DEFAULT_APP_SETTINGS.message.autoFor, ...(saved.message?.autoFor || {}) },
    },
    party: {
      ...DEFAULT_APP_SETTINGS.party,
      ...(saved.party || {}),
      additionalFields:
        Array.isArray(saved.party?.additionalFields) && saved.party.additionalFields.length === 4
          ? saved.party.additionalFields
          : DEFAULT_APP_SETTINGS.party.additionalFields,
    },
    item: {
      ...DEFAULT_APP_SETTINGS.item,
      ...(saved.item || {}),
      customFields: Array.isArray(saved.item?.customFields) ? saved.item.customFields : [],
    },
    serviceReminder: { ...DEFAULT_APP_SETTINGS.serviceReminder, ...(saved.serviceReminder || {}) },
    accounting: { ...DEFAULT_APP_SETTINGS.accounting, ...(saved.accounting || {}) },
  };
}
