import { AppDatabase, Voucher, VoucherLine } from '../types/accounting';
import { calculateVoucherLine } from '../utils/formatters';

function buildSampleVoucher(
  partial: Omit<Voucher, 'subTotal' | 'taxTotal' | 'grandTotal' | 'discountTotal' | 'roundOff'> & {
    rawLines: {
      itemId: string;
      itemName: string;
      hsn: string;
      qty: number;
      unit: string;
      rate: number;
      discountPct: number;
      taxRate: number;
      cessRate?: number;
      batchNo?: string;
    }[];
  }
): Voucher {
  const isInter = Boolean(partial.isInterState);
  const lines: VoucherLine[] = partial.rawLines.map((rl, idx) =>
    calculateVoucherLine({
      id: `${partial.id}_l_${idx}`,
      itemId: rl.itemId,
      itemName: rl.itemName,
      hsn: rl.hsn,
      qty: rl.qty,
      unit: rl.unit,
      rate: rl.rate,
      discountPct: rl.discountPct,
      taxRate: rl.taxRate,
      cessRate: rl.cessRate || 0,
      taxInclusive: false,
      isInterState: isInter,
      batchNo: rl.batchNo,
    })
  );
  const subTotal = Number(lines.reduce((s, l) => s + l.taxableAmount, 0).toFixed(2));
  const taxTotal = Number(lines.reduce((s, l) => s + l.cgst + l.sgst + l.igst + l.cess, 0).toFixed(2));
  const discountTotal = Number(
    lines.reduce((s, l) => s + (l.qty * l.rate * l.discountPct) / 100, 0).toFixed(2)
  );
  const exactTotal = subTotal + taxTotal + partial.additionalCharges;
  const grandTotal = Math.round(exactTotal);
  const roundOff = Number((grandTotal - exactTotal).toFixed(2));
  const { rawLines: _omit, ...rest } = partial;
  return {
    ...rest,
    lines,
    discountTotal,
    subTotal,
    taxTotal,
    roundOff,
    grandTotal,
  };
}

